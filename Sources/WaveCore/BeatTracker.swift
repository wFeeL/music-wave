    /// Показ через долю выключается при периоде выше `everyOtherPeriod` в столько раз (0.42 -> 0.43 с):
    /// у 143 BPM с колебанием периода ±1 % без запаса показ переключался 18 раз за 30 с.
    static let everyOtherRelease = 1.025
    /// Защелка `shownParityLeads`: включается при отношении от `everyOtherLockRatio` (2.5), выключается
    /// ниже него, умноженного на это число (2.0). Без защелки одно попадание скрытой четности переводило
    /// отношение через 2.5, и опубликованная уверенность, горб пульса, мягкое подтверждение бочки и
    /// проверки «уверенного захвата» прыгали (скрытая четность попадает через две на третью: 14
    /// переключений за 16 с, с защелкой 0). GTZAN tune (steady): точность всех вспышек 0.8688 -> 0.8689,
    /// вспышек в долю +2, мимо долей всего / с захватом 2131 / 551 те же, wrongLock 12 / 215; записи
    /// владельца те же. Выключение ниже 1.5 (0.6): мимо долей 2135 / 553.
    static let parityLeadRelease = 0.8
    private static let floorDB: Float = -120

    public let framesPerSecond: Double
    public let parameters: Parameters
    /// Звук после тишины тот же трек (пауза плеера в известном треке): перезапуск с памятью темпа
    /// (`silenceRestart`). Ставит приложение по памяти трека (`TrackTempoMemory.keepsTempo`); у всего звука
    /// системы и без трека false, и трекер начинается заново целиком.
    public var keepsTempoAfterSilence = false
    /// Режим свечения (`GlowMode`): какие события идут в расписание. Анализ, сетка, захват и пульс от него
    /// не зависят, поэтому режим можно менять на ходу. По умолчанию `rhythm`, расписание как в 1.3.
    public var glowMode = GlowMode.rhythm

    private var tempo: TempoEstimator
    /// Второе мнение о фазе (real-time PLP) на той же широкополосной функции онсетов.
    private var plp: PLPTracker
    private let hopDuration: Double
    /// Время потока следующей оценки темпа, `nil` до первого шага.
    private var nextUpdate: Double?
    /// «Сейчас», `endTime` последнего шага.
    private(set) var now = 0.0

    /// Кольцо широкополосной функции онсетов для гребенки фазы.
    private var odfRing: [Float]
    private var odfWrite = 0
    private var odfCount = 0

    /// Период доли, секунды; `nil` до первой оценки темпа.
    private(set) var period: Double?
    /// Следующая предсказанная доля, окно совпадения которой еще открыто.
    private(set) var nextBeat: Double?
    private var nextMatched = false
    /// Яркость `nextBeat`, зафиксированная, когда время потока дошло до доли. Бочка на самой доле
    /// открывает ворот уже после того, как рендер начал вспышку; без фиксации яркость того же id
    /// выросла бы посреди вспышки и дала вторую.
    private var committedAmplitude: Float?
    private(set) var confidence = 0.0
    private(set) var hits = 0
    /// Уверенность и серия попаданий по четности id доли (`everyOtherLockRatio`): при показе через
    /// долю каждая четность считает только свои доли, без показа обе повторяют `confidence` и `hits`.
    private(set) var parityConfidence = SIMD2<Double>(repeating: 0)
    /// Четность, для которой включена защелка `shownParityLeads`; `nil`, пока она выключена.
    private var parityLeadOn: UInt64?
    private var parityHits = SIMD2<Int>(repeating: 0)
    private(set) var locked = false
    /// Почему захват потерян в последний раз; `nil`, если захвата еще не было (и после `reset()` без
    /// захвата). Меняется только при потере захвата: смена темпа без захвата причину не трогает,
    /// `reset()` и `reconfigure` посреди захвата дают `.reset`.
    public internal(set) var lastUnlockReason: UnlockReason?
    /// Проверок подряд, на которых предлагающий (гребенка или PLP) расходится с ФАПЧ.
    private(set) var disagreements = 0
    /// Последнюю проверку предлагал PLP (`plpShadow`), а не гребенка. Смена предлагающего начинает
    /// счет `disagreements` заново: один голос гребенки и один голос PLP подряд не запускают тень.
    private(set) var proposedByPLP = false
    /// Период, по которому гребенка ищет фазу после `reset(keepTempo: true)`, пока у нового потока
    /// нет своей оценки темпа; `nil` без памяти.
    private var resumePeriod: Double?
    /// С последнего сброса были шаги: следующий сброс с памятью делит уверенность. Без шагов между
    /// сбросами (несколько причин одной паузы) память остается как есть.
    private var processedSinceReset = false
    /// Последние доли прошли накатом (`isCoasting`): следующая закрытая доля решает судьбу захвата.
    private var coasted = false
    /// Доли наката с широкополосным онсетом: среднее с шагом `confidenceGain` по долям, закрытым на
    /// накате (промахи тоже идут), 0 вне наката. Высота горба пульса в брейке без бочки (`ambient`).
    private(set) var coastConfidence = 0.0
    /// Теневая фаза: следующая доля другой фазы того же периода, которую гребенка предложила вместо
    /// мгновенного скачка. Считает попадания по тем же широкополосным онсетам; `nil`, пока гонки нет.
    private(set) var shadowNext: Double?
    private var shadowMatched = false
    private(set) var shadowConfidence = 0.0
    private(set) var shadowHits = 0
    /// Закрытых долей тени и сколько из последних подряд она впереди текущей фазы.
    private var shadowBeats = 0
    private var shadowLead = 0
    private var shadowVotes = 0
    /// Доводы гонки (`raceEvidenceChecks`): проверок с ее начала, из них за тень, сумма отношений
    /// оценки гребенки у тени к оценке у ФАПЧ и попадания тени.
    private(set) var raceChecks = 0
    private var raceFavour = 0
    private var raceRatioSum = 0.0
    private var raceShadowHits = 0
    /// Среднее со спадом проверок, на которых гребенка за «и» (`raceStartRatio`).
    private var raceStartEvidence = 0.0
    /// Онсеты на «и» сетки (у `nextBeat − T/2`): было ли в текущей доле и их среднее по долям с шагом
    /// `confidenceGain`, как у уверенности.
    private var halfMatched = false
    private(set) var halfConfidence = 0.0
    /// Отношение лучшей оценки гребенки к оценке у фазы ФАПЧ на последней проверке темпа
    /// (`BeatSchedule.combRatio`); `nil` до первой проверки с сеткой.
    private(set) var combRatio: Double?
    private var strengthEMA: Float = 0
    /// Id доли `nextBeat`, у `nextBeat + T` на 1 больше.
    private var beatCounter: UInt64 = 0
    private var onsetCounter: UInt64 = 0
    /// Октава показа (`everyOtherPeriod`): вспыхивают только предсказанные доли с этой четностью id,
    /// `nil` показывает все.
    private(set) var shownParity: UInt64?

    private var kickGateDB = BeatTracker.floorDB
    private var longPeakDB = BeatTracker.floorDB
    private let longFallPerHopDB: Float
    /// Энергетический ворот g_E последнего шага, 0...1.
    public private(set) var energyGate: Float = 0
    /// Вес показа 0...1: яркость предсказанных долей и приглушение онсетов бочки (`BeatSchedule.weight`).
    private(set) var displayWeight: Float = 0
    /// Короткая огибающая и длинное среднее уровня полосы бочки (амплитуда) для слышимости горба
    /// пульса; первый шаг ставит обе на свой уровень.
    private var ambientShort = AttackRelease(attack: BeatTracker.ambientLevelAttack, release: BeatTracker.ambientLevelRelease)
    private var ambientLong = AttackRelease(attack: BeatTracker.ambientAverage, release: BeatTracker.ambientAverage)
    private var ambientPrimed = false
    /// Сила последних атак для энергии пульса: скачком вверх до силы онсета, спад с `ambientRelease`.
    private var ambientHeld: Float = 0
    private var ambientRise = AttackRelease(attack: BeatTracker.ambientAttack, release: 0)
    private let ambientFallPerHop: Float
    /// Множитель горба мягкого пульса 0...1: со звуком 1, в тишине (`HopResult.silent`) идет к 0 за
    /// `silenceFade`, со звуком обратно к 1 за то же время. Сброс ставит 1.
    private(set) var soundPresence: Float = 1
    /// Шаг `soundPresence` за шаг анализа.
    private let soundPresencePerHop: Float
    /// Энергия мягкого пульса последнего шага (`AmbientInfo.energy`); относится к окну этого шага.
    /// Анализ кладет ее в кадр шага (`WaveFrame.kickEnergy`), рендер берет ее из кадра на момент показа.
    public private(set) var ambientEnergy: Float = 0

    /// Прошедшие события по времени, не больше `pastCapacity`.
    private var past: [GlowEvent]
    /// Шагов в окне медианы подтверждения и место под ее расчет.
    private let confirmHops: Int
    private var confirmScratch: [Float]
    /// Реактивный слой: детектор и последние события (`reactiveCapacity`). Детектор работает в любом режиме,
    /// поэтому смена режима на ходу видна сразу; в расписание события идут только в `hybrid` и `sound`.
    private var reactiveDetector: ReactiveGlow
    private var reactivePast: [ReactiveEvent]
    private var reactiveCounter: UInt64 = 0

    /// Реактивное событие: сила 0.5...1 (полная яркость «По звуку»).
    private struct ReactiveEvent: Sendable {
        var id: UInt64
        var time: Double
        var strength: Float
    }

    public init(framesPerSecond: Double, parameters: Parameters = .init()) {
        precondition(framesPerSecond > 0, "framesPerSecond must be positive")
        self.framesPerSecond = framesPerSecond
        self.parameters = parameters
        hopDuration = 1 / framesPerSecond
        tempo = TempoEstimator(framesPerSecond: framesPerSecond)
        plp = PLPTracker(framesPerSecond: framesPerSecond)
        // Гребенке нужно (зубцов + 1) самых длинных периодов и шаг запаса; ФАПЧ может чуть вытянуть период.
        let longest = 1.1 * 60 / TempoEstimator.minBPM
        odfRing = [Float](repeating: 0, count: Int((Double(Self.phaseTeeth + 1) * longest * framesPerSecond).rounded(.up)) + 4)
        // Спад огибающей exp(−t / 10 с) в децибелах: 20 / ln 10 дБ на постоянную времени.
        longFallPerHopDB = Float(20 / log(10.0) / (Self.longRelease * framesPerSecond))
        ambientFallPerHop = Float(exp(-1 / (Self.ambientRelease * framesPerSecond)))
        soundPresencePerHop = Float(1 / (Self.silenceFade * framesPerSecond))
        past = []
        past.reserveCapacity(Self.pastCapacity + 1)
        confirmHops = max(Int((Self.confirmWindow * framesPerSecond).rounded()), 1)
        confirmScratch = [Float](repeating: 0, count: confirmHops)
        reactiveDetector = ReactiveGlow(framesPerSecond: framesPerSecond)
        reactivePast = []
        reactivePast.reserveCapacity(Self.reactiveCapacity + 1)
    }

    /// Расписание в секундах потока: до 8 прошедших событий и две следующие предсказанные доли. В режиме
    /// `GlowMode.sound` доли идут с яркостью 0 (сетка видна журналу и диагностике, но не светится), а онсетов
    /// бочки нет.
    public var schedule: BeatSchedule {
        var events = past
        if let nextBeat, let period {
            events.append(GlowEvent(id: beatCounter, time: nextBeat, amplitude: nextAmplitude, predicted: true))
            events.append(
                GlowEvent(id: beatCounter + 1, time: nextBeat + period, amplitude: predictedAmplitude(id: beatCounter + 1), predicted: true)
            )
        }
        if glowMode == .sound {
            events.removeAll { !$0.predicted && !$0.reactive }
            for index in events.indices where events[index].predicted {
                events[index].amplitude = 0
            }
        }
        if glowMode != .rhythm {
            let scale: Float = glowMode == .sound ? 1 : ReactiveGlow.hybridScale
            for event in reactivePast {
                events.append(GlowEvent(id: event.id, time: event.time, amplitude: event.strength * scale, predicted: false, reactive: true))
            }
        }
        events.sort { $0.time < $1.time }
        return BeatSchedule(
            events: events,
            bpm: period.map { 60 / $0 },
            period: period,
            confidence: gridConfidence,
            locked: locked,
            unlockReason: locked ? nil : lastUnlockReason,
            weight: displayWeight,
            ambient: ambient,
            race: shadowNext.map { RaceInfo(shadow: $0, dim: parameters.raceDim) },
            combRatio: combRatio
        )
    }

    /// Вход мягкого пульса: сетка ФАПЧ (без темпа период 0) и высота горба `уверенность × g_E` (0 в
    /// тишине). Энергия 0: она относится к звуку, который слышен только через задержку вывода, и идет
    /// к рендеру в кадре (`WaveFrame.kickEnergy`), иначе пульс опережал бы бочку.
    ///
    /// На накате (`isCoasting`, брейк без бочки при захвате) ворот закрыт, и горб высотой
    /// `уверенность × g_E` гас, хотя хэты или малый держали долю (разбор журналов 1.2.1, исправление D).
    /// Там высота `уверенность × coastConfidence`: доля наката с широкополосным онсетом поднимает горб, доля
    /// без него опускает, так что в брейке с одним пэдом горба нет. Слышимость полосы бочки на накате не
    /// нужна (онсеты есть только от -60 dBFS). Только пульс: сетка наката не вспыхивает. Синтетика
    /// разбора (240 с, 120 BPM, брейк без бочки 120-135 с, хэты восьмыми): пульс от 0.05 в брейке на
    /// 57 % кадров при задержке вывода 134 мс (61 % при 20 мс), только от атак 48 % (45 %), с энергией от
    /// отношения уровней 0.2 %; вспышки и `wave-eval` те же.
    ///
    /// В тишине высота обеих веток умножается на `soundPresence`: горб гаснет за `silenceFade` и стоит
    /// на нуле, пока звука нет, даже если захват идет накатом.
    private var ambient: AmbientInfo {
        guard let nextBeat, let period else { return AmbientInfo(anchor: 0, period: 0, confidence: 0, energy: 0) }
        if isCoasting {
            let height = Float(gridConfidence * coastConfidence) * soundPresence
            return AmbientInfo(anchor: nextBeat, period: period, confidence: height, energy: 0)
        }
        guard ambientAudible else { return AmbientInfo(anchor: 0, period: 0, confidence: 0, energy: 0) }
        let height = Float(gridConfidence) * energyGate * soundPresence
        return AmbientInfo(anchor: nextBeat, period: period, confidence: height, energy: 0)
    }

    /// Показанная четность попадает заметно чаще скрытой (`everyOtherLockRatio`): решения о захвате
    /// идут и по ее долям.
    private var shownParityLeads: Bool {
        guard parameters.everyOtherLockRatio > 0, let shown = shownParity else { return false }
        return parityLeadOn == shown
    }

    /// Защелка `shownParityLeads` после каждого изменения уверенности по четности или показанной четности.
    private mutating func latchParityLead() {
        guard parameters.everyOtherLockRatio > 0, let shown = shownParity else {
            parityLeadOn = nil
            return
        }
        let index = Int(shown)
        let ratio = parameters.everyOtherLockRatio * (parityLeadOn == shown ? Self.parityLeadRelease : 1)
        parityLeadOn = parityConfidence[index] >= ratio * parityConfidence[1 - index] ? shown : nil
    }

    /// Уверенность для захвата, веса показа и защиты захвата: при `shownParityLeads` большая из
    /// уверенности всех долей и уверенности показанных.
    var gridConfidence: Double {
        guard shownParityLeads, let shown = shownParity else { return confidence }
        return max(confidence, parityConfidence[Int(shown)])
    }

    /// Серия попаданий для захвата и роста веса, как `gridConfidence`.
    private var gridHits: Int {
        guard shownParityLeads, let shown = shownParity else { return hits }
        return max(hits, parityHits[Int(shown)])
    }

    /// Длинное среднее уровня бочки не ниже `ambientFloorDB`.
    private var ambientAudible: Bool {
        ambientPrimed && ambientLong.value >= Self.ambientFloorAmplitude
    }

    /// `ambientFloorDB` в амплитуде.
    private static let ambientFloorAmplitude = Float(pow(10.0, Double(ambientFloorDB) / 20))

    /// Трекер идет по памяти темпа после `reset(keepTempo: true)`: у нового потока еще нет своей
    /// оценки темпа.
    public var resumingTempo: Bool { resumePeriod != nil }

    public mutating func process(_ hop: HopResult) {
        if hop.soundReturned, parameters.silenceRestart, processedSinceReset {
            // Звук после тишины: другой трек или то же место после паузы, фаза прежней сетки ничего не значит.
            reset(keepTempo: keepsTempoAfterSilence)
        }
        now = hop.endTime
        processedSinceReset = true
        soundPresence = hop.silent
            ? max(soundPresence - soundPresencePerHop, 0)
            : min(soundPresence + soundPresencePerHop, 1)
        // Ворот и вес здесь еще от прошлого шага, до звука самой доли.
        if committedAmplitude == nil, let nextBeat, now >= nextBeat {
            committedAmplitude = predictedAmplitude(id: beatCounter)
        }
        let odf = hop.broadbandODF.isFinite ? max(hop.broadbandODF, 0) : 0
        tempo.append(odf, kick: hop.kickODF)
        plp.process(odf: odf)
        odfRing[odfWrite] = odf
        odfWrite = (odfWrite + 1) % odfRing.count
        odfCount = min(odfCount + 1, odfRing.count)

        let interval = TempoEstimator.updateInterval
        if let due = nextUpdate, now >= due {
            // После долгого разрыва в потоке следующая оценка считается от «сейчас».
            nextUpdate = due + interval > now ? due + interval : now + interval
            if !isCoasting {
                if let estimate = tempo.update() {
                    resumePeriod = nil
                    updateTempo(estimate)
                } else if let resumePeriod, Double(odfCount) * hopDuration >= Self.resumeHistoryBeats * resumePeriod {
                    // Память темпа: прежний период как оценка без смены, фазу ставит гребенка.
                    updateTempo(TempoEstimate(period: resumePeriod, switched: false))
                }
            }
            updateDisplayOctave()
        } else if nextUpdate == nil {
            nextUpdate = now + interval
        }

        if let onset = hop.broadbandOnset {
            correctShadow(with: onset)
            correct(with: onset)
        }
        closeWindows()
        closeShadowWindows()
        updateGate(hop.kickLevelDB)
        updateAmbient(hop)
        updateWeight()
        if let onset = hop.kickOnset, !onset.sustained {
            addKickOnset(onset)
        }
        let reactive = reactiveDetector.process(hop, odf: odf)
        if let bass = reactive.bass { addReactive(bass) }
        if let accent = reactive.accent { addReactive(accent) }
    }

    /// Пауза, перемотка или смена источника: темп, фаза, уверенность и ворот начинаются заново.
    /// Счетчики id не сбрасываются, новые доли получают новые id. Захват, который был, теряется с
    /// причиной `.reset`.
    ///
    /// `keepTempo` (пауза в том же треке): если темп есть, остаются период, уверенность × 0.5, захват
    /// в счете попаданий (не меньше `lockHits`, без захвата 0), средняя сила онсетов и период
    /// `TempoEstimator`. Новый захват тогда идет от первого попадания, как только уверенность дойдет
    /// до `lockConfidence`. Повторный сброс без шагов между ними память не меняет.
    public mutating func reset(keepTempo: Bool = false) {
        var kept: (period: Double, confidence: Double, hits: Int, strength: Float)?
        if keepTempo, let period {
            if processedSinceReset {
                kept = (period, confidence * 0.5, locked ? max(hits, parameters.lockHits) : 0, strengthEMA)
            } else {
                kept = (period, confidence, hits, strengthEMA)
            }
        }
        tempo.reset(keepPeriod: kept != nil)
        plp.reset()
        nextUpdate = nil
        now = 0
        for index in odfRing.indices {
            odfRing[index] = 0
        }
        odfWrite = 0
        odfCount = 0
        period = nil
        nextBeat = nil
        nextMatched = false
        committedAmplitude = nil
        confidence = 0
        hits = 0
        parityConfidence = .zero
        parityLeadOn = nil
        parityHits = .zero
        lastUnlockReason = locked ? .reset : nil
        locked = false
        disagreements = 0
        proposedByPLP = false
        raceStartEvidence = 0
        halfMatched = false
        halfConfidence = 0
        combRatio = nil
        coasted = false
        coastConfidence = 0
        shownParity = nil
        dropShadow()
        strengthEMA = 0
        beatCounter += 2
        kickGateDB = Self.floorDB
        longPeakDB = Self.floorDB
        energyGate = 0
        displayWeight = 0
        ambientShort.reset()
        ambientLong.reset()
        ambientPrimed = false
        ambientHeld = 0
        ambientRise.reset()
        ambientEnergy = 0
        soundPresence = 1
        past.removeAll(keepingCapacity: true)
        reactiveDetector.reset()
        reactivePast.removeAll(keepingCapacity: true)
        resumePeriod = kept?.period
        processedSinceReset = false
        if let kept {
            period = kept.period
            confidence = kept.confidence
            hits = kept.hits
            strengthEMA = kept.strength
        }
    }

    /// Новая частота шагов (смена частоты дискретизации): все состояние начинается заново, как после
    /// `reset()`, а счетчики id продолжают расти, чтобы `BeatGlow` не принял новые события за старые.
    /// Захват, который был, теряется с причиной `.reset`. Режим свечения остается.
    public mutating func reconfigure(framesPerSecond: Double) {
        precondition(framesPerSecond > 0, "framesPerSecond must be positive")
        let beats = beatCounter
        let onsets = onsetCounter
        let reactives = reactiveCounter
        let wasLocked = locked
        let mode = glowMode
        self = BeatTracker(framesPerSecond: framesPerSecond, parameters: parameters)
        beatCounter = beats + 2
        onsetCounter = onsets
        reactiveCounter = reactives
        glowMode = mode
        if wasLocked { lastUnlockReason = .reset }
    }

    // MARK: Темп и фаза

    /// Новая оценка темпа (внутренняя, чтобы тесты подавали смену темпа напрямую).
    mutating func updateTempo(_ estimate: TempoEstimate) {
        // Период ФАПЧ каждые 0.25 с заменяется оценкой темпа, поэтому поправки `beta` между оценками
        // не накапливаются и петля ведет себя как петля первого порядка: ошибка оценки периода δ за
        // долю оставляет постоянный сдвиг фазы около δ / alpha (на 120 BPM оценка 0.4989 с вместо
        // 0.5 с, доли предсказываются примерно на 5 мс раньше онсетов). Это укладывается в допуск
        // среднего сдвига; если понадобится убрать смещение, оценка должна подтягивать T, а не
        // заменять его (`beat-sync.md` 2.5).
        let previous = period
        period = estimate.period
        // Оценка гребенки у фазы ФАПЧ нужна и при смене темпа (перенос с новой фазой, `carry`). Тогда
        // она берется от последней прошедшей доли ФАПЧ: от будущей доли зубцы нового периода уходят
        // назад мимо прошлых атак старого.
        var current = nextBeat
        if estimate.switched, let next = nextBeat, let previous, next > now {
            current = next - previous
        }
        let comb = phaseCandidate(period: estimate.period, current: current)
        if let comb, current != nil, comb.currentScore > 0 {
            combRatio = comb.score / comb.currentScore
        }
        guard let nextBeat, !estimate.switched else {
            dropShadow()
            if let nextBeat, let previous, let comb, carry(from: previous, next: nextBeat, comb: comb) { return }
            if nextBeat != nil { resetConfidence(.tempoSwitch) }
            if let comb { rephase(to: comb.time) }
            return
        }
        // Довод гонки на каждой проверке, и на той, что ее запустила.
        defer {
            if let shadow = shadowNext, let comb, comb.currentScore > 0 {
                recordRaceEvidence(shadowScore: phaseScore(at: shadow, period: estimate.period), currentScore: comb.currentScore)
            }
        }
        let plpProposal = locked && gridConfidence >= parameters.lockConfidence ? plpCandidate(period: estimate.period) : nil
        if (plpProposal != nil) != proposedByPLP {
            proposedByPLP = plpProposal != nil
            disagreements = 0
        }
        if let candidate = plpProposal {
            // Уверенный PLP вместо гребенки: тень и голоса за нее дает он.
            proposeShadow(candidate, next: nextBeat, period: estimate.period)
            return
        }
        guard let comb else { return }
        let diff = Self.circularDifference(comb.time - nextBeat, period: estimate.period)
        let stronger = comb.score > (1 + parameters.phaseJumpMargin) * comb.currentScore
        if parameters.raceStartRatio > 0, shadowNext == nil, locked, gridConfidence >= parameters.lockConfidence {
            let leans = abs(abs(diff) - estimate.period / 2) <= parameters.matchWindow * estimate.period
                && comb.score >= parameters.raceStartRatio * comb.currentScore
            raceStartEvidence += Self.raceStartGain * ((leans ? 1 : 0) - raceStartEvidence)
            if raceStartEvidence >= parameters.raceEvidenceShare, halfConfidence >= parameters.raceEvidenceShare {
                raceStartEvidence = 0
                startShadow(at: comb.time)
                return
            }
        } else {
            raceStartEvidence = 0
        }
        if abs(diff) > parameters.phaseJump * estimate.period, stronger {
            disagreements += 1
            if let shadow = shadowNext {
                let agrees = abs(Self.circularDifference(comb.time - shadow, period: estimate.period)) <= parameters.phaseJump * estimate.period
                shadowVotes = agrees ? shadowVotes + 1 : 0
            }
            if disagreements >= parameters.phaseJumpChecks, shadowNext == nil {
                if locked, gridConfidence >= parameters.lockConfidence {
                    startShadow(at: comb.time)
                } else {
                    // Уверенного захвата нет, защищать нечего: скачок сразу, как в 1.1.
                    resetConfidence(.phaseJump)
                    rephase(to: comb.time)
                }
            }
        } else {
            disagreements = 0
            shadowVotes = 0
        }
    }

    /// Уверенный захват на фазе доли `beat` (тесты гонки фаз: трекер пришел в музыку уже на «и», как в
    /// журнале 2 владельца). Тень и доводы гонки сбрасываются; без темпа ничего не делает.
    mutating func forceLock(onBeat beat: Double) {
        guard let period else { return }
        if let nextBeat, nextBeat <= now {
            archive(GlowEvent(id: beatCounter, time: nextBeat, amplitude: nextAmplitude, predicted: true))
        }
        let steps = ((now - beat) / period).rounded(.down) + 1
        nextBeat = beat + steps * period
        nextMatched = false
        committedAmplitude = nil
        beatCounter += 2
        confidence = 1
        hits = max(hits, parameters.lockHits)
        parityConfidence = SIMD2(repeating: 1)
        parityHits = SIMD2(repeating: hits)
        latchParityLead()
        locked = true
        disagreements = 0
        dropShadow()
    }

    /// Уверенный PLP вместо гребенки при уверенном захвате (`plpShadow`): расхождение его доли с ФАПЧ
    /// дальше `phaseJump` на `phaseJumpChecks` проверках подряд запускает тень, согласие PLP с тенью
    /// дает ей голоса (`raceVotes`); согласие с ФАПЧ сбрасывает счет. Гонка та же, что у гребенки.
    private mutating func proposeShadow(_ candidate: Double, next nextBeat: Double, period: Double) {
        guard abs(Self.circularDifference(candidate - nextBeat, period: period)) > parameters.phaseJump * period else {
            disagreements = 0
            shadowVotes = 0
            return
        }
        disagreements += 1
        if let shadow = shadowNext {
            let agrees = abs(Self.circularDifference(candidate - shadow, period: period)) <= parameters.phaseJump * period
            shadowVotes = agrees ? shadowVotes + 1 : 0
        }
        if disagreements >= parameters.phaseJumpChecks, shadowNext == nil {
            startShadow(at: candidate)
        }
    }

    /// Смена темпа на близкий (до `carryTolerance`) или удвоенный период (половинный темп), при которой
    /// гребенка на новом периоде видит доли там же, где ФАПЧ (до `phaseJump` меньшего периода):
    /// сетка та же, поэтому уверенность, счет попаданий и захват остаются, а следующая доля не
    /// двигается. Удвоение темпа (период вдвое короче) сбрасывает как раньше: новые доли между старыми
    /// прежняя уверенность не подтверждала, а на `Drums.tempoRamp` со слабой долей перенос сразу
    /// показывал удвоенную сетку с вспышками на «и»; на GTZAN tune без него точность всех вспышек
    /// 0.8456 -> 0.8462, вспышек с захватом мимо долей 863 -> 836. При половинном темпе гребенка
    /// выбирает, какая из двух долей остается; если не
    /// `nextBeat`, сетка начинается со следующей. При близком темпе гребенка дальше `phaseJump`, но
    /// не дальше `carryPhase` периода, дает новую фазу с той же уверенностью, если оценка гребенки выше
    /// оценки у фазы ФАПЧ больше чем на `phaseJumpMargin` (иначе фаза остается). `true`, если смена
    /// перенесена.
    private mutating func carry(
        from previous: Double, next: Double, comb candidate: (time: Double, score: Double, currentScore: Double)
    ) -> Bool {
        let comb = candidate.time
        guard let period else { return false }
        let ratio = period / previous
        let tolerance = parameters.carryTolerance
        let near = abs(ratio - 1) < tolerance
        let slower = abs(ratio / 2 - 1) < tolerance
        guard near || slower else { return false }
        let modulus = min(period, previous)
        let offset = Self.circularDifference(comb - next, period: modulus)
        if near, abs(offset) > parameters.phaseJump * modulus, abs(offset) <= parameters.carryPhase * modulus {
            // Новая фаза только с тем же запасом гребенки, что и обычный скачок; иначе фаза остается.
            if candidate.score > (1 + parameters.phaseJumpMargin) * candidate.currentScore {
                rephase(to: comb)
            }
            disagreements = 0
            return true
        }
        guard abs(offset) <= parameters.phaseJump * modulus else { return false }
        if slower, abs(Self.circularDifference(comb - next, period: period)) > parameters.phaseJump * period {
            rephase(to: next + previous)
        }
        disagreements = 0
        return true
    }

    /// Смена темпа или скачок фазы: уверенность вдвое, счет попаданий заново, захват отпущен
    /// (`beat-sync.md` 2.6), новый захват снова требует `lockHits` попаданий подряд. `reason`
    /// запоминается, только если захват был.
    private mutating func resetConfidence(_ reason: UnlockReason) {
        confidence *= 0.5
        parityConfidence *= 0.5
        latchParityLead()
        parityHits = .zero
        capWeight()
        hits = 0
        if locked { lastUnlockReason = reason }
        locked = false
    }

    /// Новая фаза: первая доля сетки `candidate` после «сейчас», новые id. Доля, которая уже началась,
    /// уходит в прошедшие события, чтобы рендер довел ее спад.
    private mutating func rephase(to candidate: Double) {
        guard let period else { return }
        if let nextBeat, nextBeat <= now {
            archive(GlowEvent(id: beatCounter, time: nextBeat, amplitude: nextAmplitude, predicted: true))
        }
        let steps = ((now - candidate) / period).rounded(.down) + 1
        nextBeat = candidate + max(steps, 0) * period
        nextMatched = false
        committedAmplitude = nil
        disagreements = 0
        beatCounter += 2
        // Новая сетка не та, что ушла после наката.
        coasted = false
    }

    /// Гонка фаз (IBT, `2026-10-25-audio-viz-and-beat.md` C.3): новая фаза гребенки идет тенью с
    /// половиной текущей уверенности, текущая сетка и захват остаются. Тень не стартует ближе
    /// `phaseJump` к текущей фазе (это та же сетка). Зовется только при уверенном захвате.
    private mutating func startShadow(at candidate: Double) {
        guard let period, let nextBeat else { return }
        let steps = ((now - candidate) / period).rounded(.down) + 1
        let first = candidate + max(steps, 0) * period
        guard abs(Self.circularDifference(first - nextBeat, period: period)) > parameters.phaseJump * period else { return }
        shadowNext = first
        shadowMatched = false
        shadowConfidence = confidence * 0.5
        shadowHits = 0
        shadowBeats = 0
        shadowLead = 0
    }

    private mutating func dropShadow() {
        shadowNext = nil
        shadowVotes = 0
        raceChecks = 0
        raceFavour = 0
        raceRatioSum = 0
        raceShadowHits = 0
        shadowConfidence = 0
        shadowHits = 0
        shadowMatched = false
        shadowBeats = 0
        shadowLead = 0
    }

    /// Закрывает окна тени: уверенность и попадания как у текущей фазы, затем счет гонки. Перехват
    /// идет при закрытии окна, когда следующая доля тени еще впереди, так что новая сетка не
    /// начинается с уже прошедшей доли.
    private mutating func closeShadowWindows() {
        while let shadow = shadowNext, let period, now > shadow + parameters.matchWindow * period {
            let hit = shadowMatched ? 1.0 : 0.0
            shadowConfidence += parameters.confidenceGain * (hit - shadowConfidence)
            shadowHits = shadowMatched ? shadowHits + 1 : 0
            if shadowMatched { raceShadowHits += 1 }
            shadowNext = shadow + period
            shadowMatched = false
            shadowBeats += 1
            shadowLead = shadowConfidence > gridConfidence + parameters.raceMargin ? shadowLead + 1 : 0
            if let nextBeat, abs(Self.circularDifference(shadow + period - nextBeat, period: period)) <= parameters.phaseJump * period {
                // Фазы сошлись: это та же сетка.
                dropShadow()
            } else if shadowLead >= parameters.raceBeats || (parameters.raceVotes > 0 && shadowVotes >= parameters.raceVotes)
                || raceEvidenceFavoursShadow
            {
                takeOverShadow()
            } else if shadowBeats >= parameters.raceLimit || raceEvidenceFavoursGrid {
                dropShadow()
            }
        }
    }

    /// Проверка темпа во время гонки: оценки гребенки у доли тени и у доли ФАПЧ.
    private mutating func recordRaceEvidence(shadowScore: Double, currentScore: Double) {
        raceChecks += 1
        if shadowScore > currentScore { raceFavour += 1 }
        raceRatioSum += shadowScore / currentScore
    }

    /// Доводы гонки за тень (`raceEvidenceChecks`): гребенка за нее на большинстве проверок с заметным
    /// перевесом в среднем, и сама тень держится на онсетах.
    private var raceEvidenceFavoursShadow: Bool {
        guard parameters.raceEvidenceChecks > 0, raceChecks >= parameters.raceEvidenceChecks, shadowBeats > 0 else {
            return false
        }
        let checks = Double(raceChecks)
        return Double(raceFavour) >= parameters.raceEvidenceShare * checks
            && raceRatioSum >= parameters.raceEvidenceRatio * checks
            && Double(raceShadowHits) >= parameters.raceEvidenceHits * Double(shadowBeats)
    }

    /// Доводы гонки за текущую сетку: после `raceEvidenceChecks` проверок среднее отношение оценок тени
    /// и ФАПЧ ниже `raceDropRatio`.
    private var raceEvidenceFavoursGrid: Bool {
        guard parameters.raceEvidenceChecks > 0, raceChecks >= parameters.raceEvidenceChecks else { return false }
        return raceRatioSum < parameters.raceDropRatio * Double(raceChecks)
    }

    /// Тень выиграла: сетка переходит на нее с ее уверенностью и счетом попаданий. Захват остается,
    /// только если счет тени сам проходит правило захвата; иначе он потерян из-за скачка фазы.
    private mutating func takeOverShadow() {
        guard let shadow = shadowNext else { return }
        if let nextBeat, nextBeat <= now {
            archive(GlowEvent(id: beatCounter, time: nextBeat, amplitude: nextAmplitude, predicted: true))
        }
        nextBeat = shadow
        nextMatched = false
        committedAmplitude = nil
        coasted = false
        beatCounter += 2
        disagreements = 0
        confidence = shadowConfidence
        parityConfidence = SIMD2(repeating: shadowConfidence)
        parityHits = SIMD2(repeating: shadowHits)
        latchParityLead()
        capWeight()
        hits = shadowHits
        let wasLocked = locked
        locked = confidence >= parameters.lockConfidence && hits >= parameters.lockHits
        if wasLocked, !locked { lastUnlockReason = .phaseJump }
        dropShadow()
        updateDisplayOctave()
    }

    /// Время последней доли по гребенке на оси онсетов и ее оценка, `nil` без энергии в истории.
    /// `currentScore` это оценка гребенки у фазы доли `current` (0 без нее).
    private func phaseCandidate(period: Double, current: Double?) -> (time: Double, score: Double, currentScore: Double)? {
        let periodHops = period * framesPerSecond
        let delays = max(Int(periodHops.rounded()), 1)
        var best = -1.0
        var bestDelay = 0
        for delay in 0..<delays {
            let score = combScore(delay: delay, periodHops: periodHops)
            if score > best {
                best = score
                bestDelay = delay
            }
        }
        guard best > 0 else { return nil }
        let currentScore = current.map { phaseScore(at: $0, period: period) } ?? 0
        return (now - Double(bestDelay) * hopDuration - StreamAnalyzer.onsetLag, best, currentScore)
    }

    /// Оценка гребенки у фазы доли `beat` (прошлой или будущей). Задержка доли от «сейчас» на оси
    /// онсетов берется по кругу периода; шаг онсета лежит от доли до шага в любую сторону, поэтому
    /// берется лучшая из трех соседних задержек.
    private func phaseScore(at beat: Double, period: Double) -> Double {
        let periodHops = period * framesPerSecond
        let delays = max(Int(periodHops.rounded()), 1)
        let age = (now - StreamAnalyzer.onsetLag - beat) / hopDuration
        let wrapped = Int((age - (age / periodHops).rounded(.down) * periodHops).rounded())
        var score = 0.0
        for delay in (wrapped - 1)...(wrapped + 1) {
            score = max(score, combScore(delay: (delay + delays) % delays, periodHops: periodHops))
        }
        return score
    }

    /// Оценка гребенки фазы для задержки `delay` шагов: зубцы через `periodHops`, у каждого максимум
    /// функции онсетов в ±1 шаге, вес каждого следующего зубца `phaseToothWeight` от предыдущего.
    private func combScore(delay: Int, periodHops: Double) -> Double {
        var score = 0.0
        var weight = 1.0
        for tooth in 0...Self.phaseTeeth {
            let center = delay + Int((Double(tooth) * periodHops).rounded())
            var peak: Float = 0
            for age in max(center - 1, 0)...(center + 1) {
                peak = max(peak, odf(age: age))
            }
            score += weight * Double(peak)
            weight *= Self.phaseToothWeight
        }
        return score
    }

    /// Широкополосная функция онсетов `age` шагов назад (0 это последний шаг), 0 вне истории.
    private func odf(age: Int) -> Float {
        guard age < odfCount else { return 0 }
        return odfRing[(odfWrite - 1 - age + 2 * odfRing.count) % odfRing.count]
    }

    /// Последняя доля PLP на оси онсетов и ее период; `nil`, пока у PLP нет оценки. Фаза PLP относится
    /// к последнему кадру функции онсетов, то есть к `now − StreamAnalyzer.onsetLag` на оси онсетов.
    var plpBeat: (time: Double, period: Double)? {
        guard let period = plp.period else { return nil }
        return (now - StreamAnalyzer.onsetLag - plp.phase * period, period)
    }

    /// Уверенность PLP последнего шага.
    var plpConfidence: Float { plp.confidence }

    /// Доля PLP как кандидат фазы сетки периода `period`: PLP уверен не ниже `plpShadow`, а его период
    /// близок к `period` или к удвоенному (`carryTolerance`). `nil` иначе.
    private func plpCandidate(period: Double) -> Double? {
        guard parameters.plpShadow > 0, Double(plp.confidence) >= parameters.plpShadow, let beat = plpBeat else { return nil }
        let ratio = beat.period / period
        guard abs(ratio - 1) < parameters.carryTolerance || abs(ratio / 2 - 1) < parameters.carryTolerance else { return nil }
        return beat.time
    }

    /// Октава показа на каждой проверке темпа и после перехвата тенью (`everyOtherPeriod`): гребенка
    /// фазы с периодом 2T на прошедших долях ФАПЧ каждой четности (`nextBeat − T`, `nextBeat − 3T`, ...
    /// и `nextBeat − 2T`, `nextBeat − 4T`, ...). Показ остается на прежней четности, пока гребенка
    /// другой не выше больше чем на `everyOtherHold`.
    private mutating func updateDisplayOctave() {
        defer { latchParityLead() }
        // Гистерезис у порога: включается ниже `everyOtherPeriod`, выключается только выше него в
        // `everyOtherRelease` раз, иначе темп у порога с дрожанием периода переключал бы показ.
        let limit = parameters.everyOtherPeriod * (shownParity == nil ? 1 : Self.everyOtherRelease)
        guard parameters.everyOtherPeriod > 0, let period, let nextBeat, period < limit else {
            shownParity = nil
            return
        }
        let periodHops = period * framesPerSecond
        let previousAge = (now - StreamAnalyzer.onsetLag - (nextBeat - period)) / hopDuration
        // Пока история не накрывает все зубцы обеих гребенок, у нечетной от `nextBeat` их больше, и
        // выбор (с удержанием) уходил бы к ней: до тех пор показ на каждой доле.
        let deepest = previousAge + (2 * Double(Self.phaseTeeth) + 1 + Self.parityReach) * periodHops + 1
        guard Double(odfCount) > deepest else {
            shownParity = nil
            return
        }
        let other = parityScore(age: previousAge, periodHops: periodHops)
        let same = parityScore(age: previousAge + periodHops, periodHops: periodHops)
        var showSame = same >= other
        if let shown = shownParity {
            let current = shown == beatCounter & 1
            if (current ? other : same) <= (1 + parameters.everyOtherHold) * (current ? same : other) {
                showSame = current
            }
        }
        shownParity = (showSame ? beatCounter : beatCounter &+ 1) & 1
    }

    /// Гребенка с периодом 2T от доли `age` шагов назад: лучшая в пределах `parityReach` периода от
    /// нее, потому что доля ФАПЧ стоит не точно на шаге пика функции онсетов.
    private func parityScore(age: Double, periodHops: Double) -> Double {
        let center = Int(age.rounded())
        let reach = max(Int((Self.parityReach * periodHops).rounded()), 1)
        var best = 0.0
        for delay in max(center - reach, 0)...max(center + reach, 0) {
            best = max(best, combScore(delay: delay, periodHops: 2 * periodHops))
        }
        return best
    }

    /// Разность по кругу периода в `(−T/2, T/2]`.
    static func circularDifference(_ difference: Double, period: Double) -> Double {
        var wrapped = difference - (difference / period).rounded() * period
        if wrapped <= -period / 2 { wrapped += period }
        if wrapped > period / 2 { wrapped -= period }
        return wrapped
    }

    // MARK: ФАПЧ и уверенность

    private mutating func correct(with onset: OnsetEvent) {
        guard let nextBeat, let period else { return }
        if abs(onset.time - (nextBeat - period / 2)) < parameters.matchWindow * period { halfMatched = true }
        let previous = nextBeat - period
        let isNext = abs(onset.time - nextBeat) <= abs(onset.time - previous)
        let error = onset.time - (isNext ? nextBeat : previous)
        guard abs(error) < parameters.matchWindow * period else { return }
        self.nextBeat = nextBeat + parameters.alpha * error
        self.period = period + parameters.beta * error
        if isNext { nextMatched = true }
        let strength = onset.strength.isFinite ? min(max(onset.strength, 0), 1) : 0
        strengthEMA += Self.strengthGain * (strength - strengthEMA)
    }

    /// Тот же онсет подстраивает фазу тени (без периода: он общий) и засчитывает ее долю.
    private mutating func correctShadow(with onset: OnsetEvent) {
        guard let shadow = shadowNext, let period else { return }
        let previous = shadow - period
        let isNext = abs(onset.time - shadow) <= abs(onset.time - previous)
        let error = onset.time - (isNext ? shadow : previous)
        guard abs(error) < parameters.matchWindow * period else { return }
        shadowNext = shadow + parameters.alpha * error
        if isNext { shadowMatched = true }
    }

    private mutating func closeWindows() {
        while let nextBeat, let period, now > nextBeat + parameters.matchWindow * period {
            let coasting = isCoasting
            coastConfidence = coasting ? coastConfidence + parameters.confidenceGain * ((nextMatched ? 1 : 0) - coastConfidence) : 0
            if coasting, !nextMatched {
                // Брейк без бочки при захвате: доля без онсета не довод против сетки, уверенность,
                // счет и захват стоят, сетка идет дальше по последнему периоду.
                coasted = true
            } else {
                let hit = nextMatched ? 1.0 : 0.0
                confidence += parameters.confidenceGain * (hit - confidence)
                halfConfidence += parameters.confidenceGain * ((halfMatched ? 1.0 : 0.0) - halfConfidence)
                hits = nextMatched ? hits + 1 : 0
                if shownParity != nil {
                    let parity = Int(beatCounter & 1)
                    parityConfidence[parity] += parameters.confidenceGain * (hit - parityConfidence[parity])
                    parityHits[parity] = nextMatched ? parityHits[parity] + 1 : 0
                } else {
                    parityConfidence = SIMD2(repeating: confidence)
                    parityHits = SIMD2(repeating: hits)
                }
                latchParityLead()
                if locked {
                    // Первая доля после брейка решает: промах значит, что сетка ушла, захват сразу
                    // отпускается. Ее вспышка зафиксирована еще при закрытом вороте и не видна.
                    locked = gridConfidence >= parameters.unlockConfidence && (nextMatched || !coasted)
                    if !locked { lastUnlockReason = .misses }
                } else {
                    locked = gridConfidence >= parameters.lockConfidence && gridHits >= parameters.lockHits
                        && phaseBeatsHalf(nextBeat, period: period)
                }
                // Атака при закрытом вороте сетку не подтверждает: решает доля с открытым воротом. После
                // промаха на ней сетка остается скрытой до попадания или новой фазы: вес показа идет от
                // уверенности, которая после одного промаха еще высока, и без этого старая сетка снова
                // светилась бы в полную силу мимо вернувшихся долей.
                if !coasting, nextMatched { coasted = false }
            }
            archive(GlowEvent(id: beatCounter, time: nextBeat, amplitude: nextAmplitude, predicted: true))
            self.nextBeat = nextBeat + period
            nextMatched = false
            halfMatched = false
            committedAmplitude = nil
            beatCounter += 1
        }
    }

    /// Проверка фазы при захвате (`lockPhaseCheck`): гребенка у «и» доли `beat` не выше гребенки у
    /// самой доли больше чем в `lockPhaseCheck` раз.
    private func phaseBeatsHalf(_ beat: Double, period: Double) -> Bool {
        guard parameters.lockPhaseCheck > 0 else { return true }
        return phaseScore(at: beat + period / 2, period: period) <= parameters.lockPhaseCheck * phaseScore(at: beat, period: period)
    }

    // MARK: Ворот, вес и события

    private mutating func updateGate(_ levelDB: Float) {
        // Бесконечность и NaN считаются полом, иначе удержание и P_long застряли бы на бесконечности.
        let level = levelDB.isFinite ? max(levelDB, Self.floorDB) : Self.floorDB
        let fall: Float
        if let period {
            // Через долю показывается каждая вторая: удержание бочки тянется на период показа, иначе
            // при бочке раз в 2T ворот к показанной доле уже закрыт.
            let shownPeriod = shownParity == nil ? period : 2 * period
            fall = parameters.gateFallPerBeatDB * Float(hopDuration / shownPeriod)
        } else {
            fall = parameters.gateFallNoTempoDB * Float(hopDuration / TempoEstimator.updateInterval)
        }
        kickGateDB = max(level, kickGateDB - fall)
        longPeakDB = max(level, longPeakDB - longFallPerHopDB)
        energyGate = Self.smoothstep(Self.gateLowDB, Self.gateHighDB, kickGateDB - longPeakDB)
    }

    /// Энергия мягкого пульса от онсетов шага и слышимость полосы бочки: ее уровень в амплитуде
    /// (нечисловой как пол) в короткую огибающую, она в длинное среднее (`ambientAudible`).
    private mutating func updateAmbient(_ hop: HopResult) {
        ambientHeld *= ambientFallPerHop
        holdAttack(hop.broadbandOnset)
        holdAttack(hop.kickOnset)
        let levelDB = hop.kickLevelDB
        let level = levelDB.isFinite ? max(levelDB, Self.floorDB) : Self.floorDB
        let amplitude = Float(pow(10.0, Double(level) / 20))
        if ambientPrimed {
            ambientShort.step(toward: amplitude, dt: hopDuration)
            ambientLong.step(toward: ambientShort.value, dt: hopDuration)
        } else {
            ambientShort.reset(to: amplitude)
            ambientLong.reset(to: amplitude)
            ambientPrimed = true
        }
        ambientEnergy = ambientRise.step(toward: ambientHeld, dt: hopDuration)
    }

    /// Сила онсета в удержание энергии пульса (нечисловая не идет, вне 0...1 обрезается).
    private mutating func holdAttack(_ onset: OnsetEvent?) {
        guard let strength = onset?.strength, strength.isFinite else { return }
        ambientHeld = max(ambientHeld, min(max(strength, 0), 1))
    }

    private mutating func updateWeight() {
        displayWeight = Self.nextWeight(
            displayWeight, confidence: gridConfidence, beats: hopDuration / (period ?? Self.defaultPeriod),
            parameters: parameters,
            rising: nextBeat != nil && (locked || gridHits >= parameters.weightHits)
        )
    }

    /// Новая сетка: вес не выше цели по ее уверенности, старый вес ее не подтверждал.
    private mutating func capWeight() {
        let target = Self.smoothstep(Float(parameters.weightLow), Float(parameters.weightHigh), Float(gridConfidence))
        displayWeight = min(displayWeight, target)
    }

    /// Вес показа после `beats` долей при уверенности `confidence`: к цели
    /// `smoothstep(weightLow, weightHigh, confidence)` не быстрее `beats / weightRiseBeats` вверх и
    /// `beats / weightFallBeats` вниз. Без `rising` вес не растет (цель не выше текущего веса).
    static func nextWeight(
        _ weight: Float, confidence: Double, beats: Double, parameters: Parameters, rising: Bool = true
    ) -> Float {
        var target = smoothstep(Float(parameters.weightLow), Float(parameters.weightHigh), Float(confidence))
        if !rising { target = min(target, weight) }
        if weight < target {
            return min(weight + Float(beats / parameters.weightRiseBeats), target)
        }
        return max(weight - Float(beats / parameters.weightFallBeats), target)
    }

    /// Накат: захват есть, а энергетический ворот ниже `coastGate` (брейк без бочки). Промахи не
    /// считаются, оценки темпа не берутся: в истории без бочки оценка плывет (на `Drums.breakdown`
    /// период уходил с 0.499 до 0.488 с, и после брейка вспышки шли на 90 мс мимо).
    private var isCoasting: Bool {
        locked && energyGate < parameters.coastGate
    }

    /// Яркость предсказанной доли `id`. После наката сетка не видна, пока доля с открытым воротом не
    /// попадет (или пока не придет новая фаза): бочка новой сетки открывает ворот раньше, чем
    /// закрывается окно старой доли. Во время гонки фаз сетка светится с `raceDim`. Доля, скрытая
    /// октавой показа (`shownParity`), не светится.
    private func predictedAmplitude(id: UInt64) -> Float {
        guard !coasted, shownParity.map({ id & 1 == $0 }) ?? true else { return 0 }
        return strengthEMA * energyGate * displayWeight * (shadowNext == nil ? 1 : parameters.raceDim)
    }

    /// Яркость `nextBeat`: зафиксированная или текущая.
    private var nextAmplitude: Float {
        committedAmplitude ?? predictedAmplitude(id: beatCounter)
    }

    private mutating func addKickOnset(_ onset: OnsetEvent) {
        if let nextBeat, let period {
            // Бочка у доли сетки отбрасывается, только если сама доля вспыхнет: иначе на передаче от
            // бочек к сетке (вес уже выше 0.5, а яркость доли еще ниже порога) доля оставалась тусклой.
            // У доли, скрытой показом через долю, бочка отбрасывается всегда: ее отблеск или вспышка
            // (пока вес растет) ломали бы ритм через долю.
            let toNext = abs(onset.time - nextBeat)
            let toPrevious = abs(onset.time - (nextBeat - period))
            if min(toNext, toPrevious) < parameters.dropWindow * period {
                let id = toNext <= toPrevious ? beatCounter : beatCounter &- 1
                if let shownParity, id & 1 != shownParity { return }
                let beatAmplitude = toNext <= toPrevious ? nextAmplitude : archivedAmplitude(id: id)
                if beatAmplitude > OfflineBeatChain.eventRise { return }
            }
        }
        let strength = onset.strength.isFinite ? min(max(onset.strength, parameters.onsetFloor), 1) : parameters.onsetFloor
        let offGrid = parameters.offGridScale + (1 - parameters.offGridScale) * (1 - displayWeight)
        let amplitude = strength * offGrid * kickConfirmation()
        guard amplitude > 0 else { return }
        archive(GlowEvent(id: Self.onsetIDFlag | onsetCounter, time: onset.time, amplitude: amplitude, predicted: false))
        onsetCounter += 1
    }

    /// Реактивное событие в расписание (`reactivePast`), id из своего счетчика. Событие ближе
    /// `ReactiveGlow.mergeWindow` к прошлому сливается с ним (тот же id, раннее время, большая сила):
    /// растущая функция онсетов дает событие на шаге подъема и еще одно, сильнее, шагом позже, а это одна
    /// атака и одна вспышка.
    private mutating func addReactive(_ event: ReactiveGlow.Event) {
        if let last = reactivePast.indices.last, event.time - reactivePast[last].time < ReactiveGlow.mergeWindow {
            reactivePast[last].time = min(reactivePast[last].time, event.time)
            reactivePast[last].strength = max(reactivePast[last].strength, event.strength)
            return
        }
        reactivePast.append(ReactiveEvent(id: Self.reactiveIDFlag | reactiveCounter, time: event.time, strength: event.strength))
        reactiveCounter += 1
        if reactivePast.count > Self.reactiveCapacity {
            reactivePast.removeFirst()
        }
    }

    /// Насколько онсет бочки похож на удар, а не на всплеск шума в трех бинах бочки, 0...1.
    ///
    /// У настоящей бочки (и в тихой музыке на -30 dBFS) широкополосная функция на шаге онсета в десятки
    /// раз выше своей медианы: между ударами лог-поток почти нулевой. Ложный онсет в розовом шуме
    /// (около 0.17 в секунду на -20 dBFS, `OnlinePeakPicker` бочки их пропускает) широкополосно не
    /// выделяется: отношение не выше примерно 5.5 при любом уровне шума. Без подтверждения такие
    /// онсеты светились бы без захвата, когда трекер еще не знает, что ритма нет.
    ///
    /// Когда темп известен и ворот открыт (`confirmGateOpen`), подтверждение для показа мягче:
    /// `max(kickConfirmFloor, smoothstep(kickConfirmLow, confirmHigh, отношение))`. Попадания для
    /// уверенности от этого не зависят, их дают только широкополосные онсеты (`correct`).
    private mutating func kickConfirmation() -> Float {
        let count = min(confirmHops, odfCount - 1)
        guard count > 0 else { return 1 }
        // Возраст 0 это шаг онсета; медиана по шагам до него.
        for age in 1...count {
            confirmScratch[age - 1] = odf(age: age)
        }
        let median = confirmScratch.withUnsafeMutableBufferPointer { buffer in
            Self.select(UnsafeMutableBufferPointer(rebasing: buffer[0..<count]), rank: count / 2)
        }
        let ratio = max(odf(age: 0), odf(age: 1)) / (median + Self.confirmEpsilon)
        if period != nil, gridConfidence >= parameters.weightLow, energyGate >= Self.confirmGateOpen {
            return max(parameters.kickConfirmFloor, Self.smoothstep(parameters.kickConfirmLow, Self.confirmHigh, ratio))
        }
        return Self.smoothstep(Self.confirmLow, Self.confirmHigh, ratio)
    }

    /// Яркость прошедшей предсказанной доли `id` из прошедших событий, 0, если ее там нет.
    private func archivedAmplitude(id: UInt64) -> Float {
        for event in past where event.predicted && event.id == id {
            return event.amplitude
        }
        return 0
    }

    private mutating func archive(_ event: GlowEvent) {
        let index = past.lastIndex { $0.time <= event.time }.map { $0 + 1 } ?? 0
        past.insert(event, at: index)
        if past.count > Self.pastCapacity {
            past.removeFirst()
        }
    }

    /// Элемент ранга `rank` (с нуля, по возрастанию), выбор Хоара на месте без выделения памяти.
    /// Порядок элементов буфера меняется.
    static func select(_ buffer: UnsafeMutableBufferPointer<Float>, rank: Int) -> Float {
        var low = 0
        var high = buffer.count - 1
        while low < high {
            let pivot = buffer[(low + high) / 2]
            var i = low
            var j = high
            while i <= j {
                while buffer[i] < pivot { i += 1 }
                while buffer[j] > pivot { j -= 1 }
                if i <= j {
                    buffer.swapAt(i, j)
                    i += 1
                    j -= 1
                }
            }
            if rank <= j {
                high = j
            } else if rank >= i {
                low = i
            } else {
                break
            }
        }
        return buffer[rank]
    }

    static func smoothstep(_ low: Float, _ high: Float, _ x: Float) -> Float {
        let t = min(max((x - low) / (high - low), 0), 1)
        return t * t * (3 - 2 * t)
    }
}
